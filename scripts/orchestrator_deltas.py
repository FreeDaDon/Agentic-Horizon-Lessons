#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = []
# ///
"""
Write what each lesson changed in the orchestrator app it inherited.

Lessons 12, 13 and 14 each carry a full copy of apps/orchestrator_3_stream and
apps/orchestrator_db so each folder runs on its own. The teaching content of 13 and 14 is
the delta, so this script renders it as a reviewable document per step, and `--check`
fails CI when a committed document no longer matches the code.

Usage: scripts/orchestrator_deltas.py [--check]
"""

from __future__ import annotations

import difflib
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APPS = ("apps/orchestrator_3_stream", "apps/orchestrator_db")
IGNORED_PARTS = {"node_modules", ".venv", "__pycache__", "logs", "dist", ".claude"}
IGNORED_SUFFIXES = {".lock", ".png", ".jpg", ".ico", ".svg"}
STEPS = (
    ("12. multi-agent-orchestration", "13. agent-experts", "05_agent_experts/orchestrator-delta-12-to-13.md"),
    ("13. agent-experts", "14.orchestrator-agent-with-adws-singularity",
     "06_building_agentic_layers/orchestrator-delta-13-to-14.md"),
)


@dataclass(frozen=True)
class Change:
    path: str
    status: str
    added: int
    removed: int


def files_under(lesson: str) -> dict[str, Path]:
    listed = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", "--", *APPS],
        cwd=ROOT / lesson, capture_output=True, text=True, check=True).stdout.splitlines()
    return {
        rel: ROOT / lesson / rel for rel in listed
        if not IGNORED_PARTS & set(Path(rel).parts) and Path(rel).suffix not in IGNORED_SUFFIXES
        and (ROOT / lesson / rel).is_file()
    }


def lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").splitlines()


def compare(old_lesson: str, new_lesson: str) -> list[Change]:
    old, new = files_under(old_lesson), files_under(new_lesson)
    changes = []
    for rel in sorted(old.keys() | new.keys()):
        if rel not in new:
            changes.append(Change(rel, "removed", 0, len(lines(old[rel]))))
        elif rel not in old:
            changes.append(Change(rel, "added", len(lines(new[rel])), 0))
        else:
            a, b = lines(old[rel]), lines(new[rel])
            if a != b:
                diff = list(difflib.unified_diff(a, b, lineterm="", n=0))
                changes.append(Change(rel, "changed",
                                      sum(1 for d in diff if d.startswith("+") and not d.startswith("+++")),
                                      sum(1 for d in diff if d.startswith("-") and not d.startswith("---"))))
    return changes


def render(old_lesson: str, new_lesson: str, changes: list[Change]) -> str:
    by_status = {s: [c for c in changes if c.status == s] for s in ("added", "changed", "removed")}
    out = [
        f"# Orchestrator delta: `{old_lesson}` → `{new_lesson}`",
        "",
        f"> **BLUF:** {len(by_status['added'])} files added, {len(by_status['changed'])} changed and "
        f"{len(by_status['removed'])} removed in `{'` and `'.join(APPS)}`. "
        "Line-ending-only differences are ignored. Generated by "
        "[`scripts/orchestrator_deltas.py`](../scripts/orchestrator_deltas.py); CI fails if this file is stale.",
        "",
        "Read the changed files with `git diff --no-index` to see the code, for example:",
        "",
        "```bash",
        f'git diff --no-index "{old_lesson}/apps/orchestrator_3_stream/backend/modules" '
        f'"{new_lesson}/apps/orchestrator_3_stream/backend/modules"',
        "```",
    ]
    for status, title in (("added", "Added"), ("changed", "Changed"), ("removed", "Removed")):
        if by_status[status]:
            out += ["", f"## {title}", "", "| File | + | − |", "|---|---:|---:|"]
            out += [f"| `{c.path}` | {c.added} | {c.removed} |" for c in by_status[status]]
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for old_lesson, new_lesson, target in STEPS:
        text = render(old_lesson, new_lesson, compare(old_lesson, new_lesson))
        path = ROOT / target
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(target)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {target}")
    if stale:
        print("stale orchestrator delta docs (run scripts/orchestrator_deltas.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
